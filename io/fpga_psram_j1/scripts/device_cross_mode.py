import sys
sys.path.append('/apps/psram_j1')
import psram
values = bytes((0x03, 0x16, 0x29, 0x4c, 0x8f, 0x52, 0xa5, 0xf8))
psram.load('/apps/psram_j1/spi_baseline.bit')
p = psram.Psram()
p.write(0x200, bytes(v ^ 255 for v in values))
print('SPI_PREFILL:', list(p.read(0x200, 8)))
p.deinit()
psram.load()
p = psram.Psram()
p.write(0x200, values)
print('QPI_WROTE:', list(values))
print('QPI_READ:', list(p.read(0x200, 8)))
p.deinit()
psram.load('/apps/psram_j1/spi_baseline.bit')
p = psram.Psram()
print('SPI_READ_QPI_DATA:', list(p.read(0x200, 8)))
p.write(0x200, values)
print('SPI_WROTE:', list(values))
print('SPI_READ:', list(p.read(0x200, 8)))
p.deinit()
psram.load()
p = psram.Psram()
print('QPI_READ_SPI_DATA:', list(p.read(0x200, 8)))
p.deinit()
