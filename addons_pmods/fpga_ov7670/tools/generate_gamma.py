"""Generate RGB gamma logic ROMs; --check detects stale generated RTL."""
import argparse
import math
from pathlib import Path

GAMMAS = (0.5, 0.625, 0.75, 0.875, 1.0, 1.25, 1.5, 1.75, 2.0)

def render():
    lines = ['// Generated by tools/generate_gamma.py. No block RAM.',
             'module isp_gamma(input wire clk, input wire [3:0] preset,',
             ' input wire [7:0] r,g,b, output reg [7:0] qr,qg,qb);',
             ' (* ram_style="logic", rom_style="logic" *) reg [7:0] lut[0:2303];',
             ' initial begin']
    for index, gamma in enumerate(GAMMAS):
        for value in range(256):
            result = math.floor(255 * (value / 255) ** (1 / gamma) + 0.5)
            lines.append(f"  lut[{index * 256 + value}]=8'd{result};")
    lines += [' end', ' always @(posedge clk) begin',
              '  qr<=lut[{preset,r}];qg<=lut[{preset,g}];qb<=lut[{preset,b}];',
              ' end', 'endmodule', '']
    return '\n'.join(lines)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'src/isp_gamma.v'
    if args.check:
        assert target.read_text() == render(), 'Run tools/generate_gamma.py'
    else:
        target.write_text(render(), newline='\n')
